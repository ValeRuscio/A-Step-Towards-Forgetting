def fixed_scale(d):
    v=d[np.triu_indices(len(d),1)];v=v[v>1e-12];return float(np.median(v)) if len(v) else 1.


def subspace(x,k):
    x=np.asarray(x,float);u,s,v=np.linalg.svd(x-x.mean(0),full_matrices=False)
    rank=min(k,int(np.sum(s>max(float(s[0]) if len(s) else 0,1e-30)*1e-7)))
    return v[:rank],s


def frame_metrics(x,x0,sens,sens0,rank):
    x=np.asarray(x,float);x0=np.asarray(x0,float);sens=np.asarray(sens,float);sens0=np.asarray(sens0,float)
    b,sv=subspace(x,rank);b0,_=subspace(x0,rank);k=min(len(b),len(b0))
    cs=np.linalg.svd(b[:k]@b0[:k].T,compute_uv=False).clip(0,1) if k else np.array([])
    dx=x-x0;ds=sens-sens0
    dn=np.linalg.norm(dx,axis=1);sn=np.linalg.norm(sens0,axis=1)
    return dict(mean_shift_norm=float(np.linalg.norm(x.mean(0)-x0.mean(0))),mean_row_norm=float(np.linalg.norm(x,axis=1).mean()),
        centered_effective_rank=entropy_rank(sv**2),top_variance_fraction=float(sv[0]**2/max(np.sum(sv**2),1e-30)),
        principal_angles_degrees=np.degrees(np.arccos(cs)).tolist(),subspace_rank_compared=k,
        per_entity_displacement_norm=dn.tolist(),sensitivity_norm=np.linalg.norm(sens,axis=1).tolist(),
        old_sensitivity_dot_displacement=np.einsum('ij,ij->i',sens0,dx).tolist(),
        current_sensitivity_dot_displacement=np.einsum('ij,ij->i',sens,dx).tolist(),
        sensitivity_change_dot_displacement=np.einsum('ij,ij->i',ds,dx).tolist(),
        old_sensitivity_displacement_cosine=(np.einsum('ij,ij->i',sens0,dx)/np.maximum(dn*sn,1e-30)).tolist(),
        spectrum=(sv**2).tolist())


def mst_edges(d,entities,targets):
    n=len(d);used={0};edges=[]
    while len(used)<n:
        dist,i,j=min((float(d[i,j]),i,j) for i in used for j in range(n) if j not in used)
        used.add(j);edges.append(dict(entity1=int(entities[i]),entity2=int(entities[j]),distance=dist,same_target=bool(targets[i]==targets[j])))
    return edges


def topology_record(x,x0,metric,entities,targets,nulls,seed):
    d=points_distance(x);d0=points_distance(x0);scale=fixed_scale(d0)
    task=points_distance(x@metric.T);task0=points_distance(x0@metric.T);ts=fixed_scale(task0)
    ph=persistent_homology(d/scale,[.25,.5,1.,1.5,2.]);tph=persistent_homology(task/ts,[.25,.5,1.,1.5,2.])
    rng=np.random.default_rng(seed);null=[];xc=x-x.mean(0);n=len(x)
    # Orthogonal mixing within the subspace perpendicular to the constant vector.
    basis=np.linalg.svd(np.ones((1,n)),full_matrices=True)[2][1:].T
    for _ in range(nulls):
        q,_=np.linalg.qr(rng.normal(size=(n-1,n-1)));xn=basis@q@basis.T@xc
        p=persistent_homology(points_distance(xn)/scale,[1.])
        null.append(dict(H0=p['H0']['finite_total_persistence'],H1=p['H1']['finite_total_persistence']))
    base_nn=np.argsort(d0,axis=1)[:,1:4];nn=np.argsort(d,axis=1)[:,1:4]
    return dict(PH=ph,task_semimetric_PH=tph,baseline_scale=scale,task_baseline_scale=ts,
        mst=mst_edges(d/scale,entities,targets),neighbor_retention=float(np.mean([len(set(a)&set(b))/len(a) for a,b in zip(nn,base_nn)])),
        spectrum_preserving_point_mixing_null=null,
        note='Frozen monitor margin-gradient map; not Fisher/Hessian. Point-mixing null preserves centered feature covariance, not entity semantics.')


def capture(e,data,s,monitor,held,ctl):
    layers=s['geometry_layers'] or list(range(e.model.config.num_hidden_layers))
    if any(l<0 or l>=e.model.config.num_hidden_layers for l in layers):raise ValueError('Requested geometry layer does not exist.')
    arrays={};meta={}
    for split in SPLITS:
        ids=monitor if split.endswith('valid') else held
        rows=[r for r in data[split] if r['entity'] in ids];meta[split]=dict(entities=[r['entity'] for r in rows],q0=[r['q'][0] for r in rows])
        per={str(l):{'x':[],'lossgrad':[],'margin_grad':[]} for l in layers};per['final']={'x':[],'lossgrad':[],'margin_grad':[]}
        for r in rows:
            ctl.check();ctl.pulse(phase='passive activation/sensitivity capture',split=split,entity=r['entity'])
            taps={};handles=[]
            for l in layers:
                def hook(mod,inp,out,key=str(l)):
                    taps[key]=out[0] if isinstance(out,tuple) else out
                handles.append(e.model.model.layers[l].register_forward_hook(hook))
            try:
                inp,q,labels=collate([r],e.tok.pad_token_id,e.c.device)
                final=e.model.model(**inp,use_cache=False,return_dict=True).last_hidden_state;taps['final']=final
                lp=e.model.lm_head(final[:,-1,:]).double().log_softmax(-1)
                loss=(q*(q.log()-lp[:,labels])).sum();margin=(lp[:,labels[0]]-lp[:,labels[1]]).sum()
                keys=list(taps);targets=[taps[k] for k in keys]
                gl=torch.autograd.grad(loss,targets,retain_graph=True)
                gm=torch.autograd.grad(margin,targets)
                for k,a,b in zip(keys,gl,gm):
                    per[k]['x'].append(taps[k][0,-1].detach().float().cpu().numpy().copy())
                    per[k]['lossgrad'].append(a[0,-1].detach().float().cpu().numpy().copy())
                    per[k]['margin_grad'].append(b[0,-1].detach().float().cpu().numpy().copy())
            finally:
                for h in handles:h.remove()
            del taps,targets,gl,gm,final,lp,loss,margin
        for k,v in per.items():
            for name,vals in v.items():arrays[f'{split}__{k}__{name}']=np.stack(vals).astype(np.float32)
    return arrays,meta


def geometry_analysis(arrays,base,previous,meta,s,seed):
    out={}
    for split,m in meta.items():
        if not split.endswith('test'):continue
        for key in [k for k in arrays if k.startswith(split+'__') and k.endswith('__x')]:
            site=key.split('__')[1];prefix=split+'__'+site+'__';calprefix=split.replace('test','valid')+'__'+site+'__'
            x=arrays[key].astype(float);x0=base[key].astype(float);sens=arrays[prefix+'lossgrad'];sens0=base[prefix+'lossgrad']
            metric=base[calprefix+'margin_grad'].astype(float)/math.sqrt(len(base[calprefix+'margin_grad']))
            entry=dict(anchor=frame_metrics(x,x0,sens,sens0,s['frame_rank']),previous=frame_metrics(x,previous[key],sens,previous[prefix+'lossgrad'],s['frame_rank']),
                topology=topology_record(x,x0,metric,m['entities'],m['q0'],s['topology_nulls'],seed),entities=m['entities'],q0=m['q0'])
            # Held-out Procrustes residual; fitting uses monitor identities only.
            a=arrays[calprefix+'x'].astype(float);b=base[calprefix+'x'].astype(float)
            joint=np.concatenate([a,b],axis=0);_,sv,v=np.linalg.svd(joint,full_matrices=False)
            rank=int(np.sum(sv>max(sv[0],1e-30)*1e-7));basis=v[:rank].T
            u,_,vh=np.linalg.svd((a@basis).T@(b@basis),full_matrices=False);r=u@vh
            aligned=x+(x@basis)@(r-np.eye(rank))@basis.T
            entry['alignment']=dict(native_mse=float(np.mean((x-x0)**2)),heldout_orthogonal_mse=float(np.mean((aligned-x0)**2)),rank=rank,includes_reflections=True)
            out[prefix]=entry
    return out


def sampled_matrices(e,s,seed):
    """Fixed coordinate samples of every unique matrix; not full spectra or MP tests."""
    out={}
    for name,p in e.params.items():
        if p.ndim!=2:continue
        rng=np.random.default_rng(int(hashlib.sha256(name.encode()).hexdigest()[:8],16))
        ri=np.sort(rng.choice(p.shape[0],min(s['matrix_sample_rows'],p.shape[0]),replace=False));ci=np.sort(rng.choice(p.shape[1],min(s['matrix_sample_cols'],p.shape[1]),replace=False))
        a=p.detach()[torch.as_tensor(ri,device=p.device)][:,torch.as_tensor(ci,device=p.device)].double().cpu().numpy()
        sv=np.linalg.svd(a-a.mean(0),compute_uv=False);observed=float(sv[0]**2/max((sv**2).sum(),1e-30));null=[]
        for _ in range(s['matrix_nulls']):
            b=np.stack([rng.permutation(a[:,j]) for j in range(a.shape[1])],axis=1);ss=np.linalg.svd(b-b.mean(0),compute_uv=False)
            null.append(float(ss[0]**2/max((ss**2).sum(),1e-30)))
        out[name]=dict(shape=list(p.shape),sample_rows=ri.tolist(),sample_cols=ci.tolist(),centered_sample_singular_values=sv.tolist(),
            sample_effective_rank=entropy_rank(sv**2),top_fraction=observed,independent_column_shuffle_top_fraction=null)
    return out


