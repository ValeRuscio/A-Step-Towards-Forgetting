def launch(s):
    import fcntl
    validate(s);out=Path(s['output']);out.mkdir(parents=True,exist_ok=True)
    with (out/'launch.lock').open('a') as f:
        fcntl.flock(f,fcntl.LOCK_EX)
        if alive(out):print('Already running. Use refresh() to inspect progress.');return str(out)
        old=read(out/'settings.json')
        if old and identity(old)!=identity(s):
            # New settings create a sibling run automatically; never erase old results.
            out=out.with_name(out.name+'_'+time.strftime('%Y%m%d_%H%M%S')+'_'+uuid.uuid4().hex[:4]);out.mkdir();s['output']=str(out)
            print('Settings changed; using a new output directory:',out)
        atomic_json(s,out/'settings.json');(out/'STOP').unlink(missing_ok=True)
        for p in Path(__file__).parent.glob('*.py'):
            target=out/'code'/p.name;target.parent.mkdir(exist_ok=True);shutil.copy2(p,target)
        atomic_json(dict(files={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in Path(__file__).parent.glob('*.py')},source_config=read(Path(s['source'])/'config.json')),out/'provenance.json')
        atomic_json(dict(status='launching',last_progress=time.time()),out/'status.json')
        with (out/'worker.log').open('a') as log:
            proc=subprocess.Popen([sys.executable,str(out/'code/natural_geometry.py'),'--worker',str(out/'settings.json')],stdout=log,stderr=subprocess.STDOUT,start_new_session=True)
        atomic_json(dict(pid=proc.pid),out/'process.json')
        # Keep launch lock until worker acquires its lifetime lock or exits.
        for _ in range(100):
            if alive(out) or proc.poll() is not None:break
            time.sleep(.1)
        print('Started/resumed:',out);return str(out)


def stop(output):
    out=Path(output);out.mkdir(parents=True,exist_ok=True);(out/'STOP').touch()
    print('Stop requested. The worker will save at a safe boundary; refresh until alive is false. Do not use restart to resume.')


def restart(s):
    if alive(s['output']):stop(s['output']);print('Wait for the stop to finish, then call restart again.');return None
    out=Path(s['output']);s['output']=str(out.with_name(out.name+'_fresh_'+time.strftime('%Y%m%d_%H%M%S')))
    return launch(s)


