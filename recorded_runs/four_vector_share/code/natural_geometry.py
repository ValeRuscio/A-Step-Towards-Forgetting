def validate(s):
    if s.get('version')!=VERSION:raise ValueError('Use settings generated by defaults() from this release.')
    c=Config(**read(Path(s['source'])/'config.json'))
    for k in ['chunk_steps','checkpoint_every','geometry_every','derivative_every','monitor_entities','topology_entities','eval_batch','threads','frame_rank','matrix_sample_rows','matrix_sample_cols']:
        if not isinstance(s[k],int) or s[k]<1:raise ValueError(k+' must be a positive integer')
    if not s['seeds'] or len(set(s['seeds']))!=len(s['seeds']):raise ValueError('Provide distinct available seeds.')
    if not 0<=s['start_step']<s['end_step']<=c.b_steps:raise ValueError(f'Need 0 <= start_step < end_step <= source b_steps ({c.b_steps}).')
    if s['hours']*60<=s['reserve_minutes']:raise ValueError('Time budget must exceed reserve.')
    if s['curvature_every']<0 or s['curvature_entities']<1:raise ValueError('Invalid curvature settings.')
    if s['monitor_entities']+s['topology_entities']>c.entities or s['topology_entities']>32:raise ValueError('Monitor and topology identities must be disjoint; PH supports <=32 landmarks.')
    if not c.smoke and not Path(c.model).exists() and (len(c.revision)!=40 or any(x not in '0123456789abcdef' for x in c.revision.lower())):raise ValueError('Original config must contain its pinned 40-character HF revision. Do not replace it with main.')
    for seed in s['seeds']:
        for f in ['anchor.pt','data.json']:
            if not (Path(s['source'])/f'seed{seed}'/f).exists():raise FileNotFoundError(f'Missing seed{seed}/{f}')
    if c.transition not in ['keep','reset']:raise ValueError('Unknown original transition policy.')
    c.device=s['device'];c.threads=s['threads'];return c


class Pause(Exception):pass
class Control:
    def __init__(self,s):
        self.s=s;self.out=Path(s['output']);self.start=time.time();self.deadline=self.start+s['hours']*3600-s['reserve_minutes']*60
        self.last_check=0;self.phase={};self.last_progress=time.time()
    def pulse(self,**fields):
        self.phase.update(fields);self.last_progress=time.time()
        atomic_json(dict(status='running',last_progress=self.last_progress,**self.phase),self.out/'status.json')
    def check(self):
        if (self.out/'STOP').exists():raise Pause('Stop requested')
        if time.time()>self.deadline:raise Pause('Session time budget reached')
        if shutil.disk_usage(self.out).free<self.s['minimum_free_gb']*1024**3:raise Pause('Disk reserve reached')
    def storage(self):
        size=sum(p.stat().st_size for p in self.out.rglob('*') if p.is_file() and p.suffix not in ['.pt','.tmp'])
        if size>self.s['max_measurement_gb']*1024**3:raise Pause('Measurement storage budget reached; increase max_measurement_gb to resume')


