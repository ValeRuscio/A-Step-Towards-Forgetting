def mean_gradient(e,rows):
    e.opt.zero_grad(set_to_none=True)
    for i in range(0,len(rows),e.c.microbatch):
        (e.loss_rows(rows[i:i+e.c.microbatch]).sum()/len(rows)).backward()
    result={n:p.grad.detach().cpu().clone() for n,p in e.params.items() if p.grad is not None}
    e.opt.zero_grad(set_to_none=True);return result


def channels(e):
    """Native Adam history/current numerator terms, shared updated denominator.
    Only ordinary Adam with zero weight decay is admitted by the copied engine.
    """
    hist={};cur={}
    for pg in e.opt.param_groups:
        if pg.get('weight_decay',0)!=0 or pg.get('amsgrad',False) or pg.get('maximize',False):raise ValueError('Unsupported optimizer variant; decomposition refused.')
        b1,b2=pg['betas'];lr=pg['lr'];eps=pg['eps']
        for p in pg['params']:
            if p.grad is None:continue
            st=e.opt.state[p];t=int(st['step'].item())+1 if 'step' in st else 1
            m=st.get('exp_avg',torch.zeros_like(p));v=st.get('exp_avg_sq',torch.zeros_like(p))
            den=(b2*v+(1-b2)*p.grad.square()).sqrt()/math.sqrt(1-b2**t)+eps
            fac=-lr/(1-b1**t)
            name=next(n for n,q in e.params.items() if q is p)
            hist[name]=(fac*b1*m/den).detach().cpu()
            cur[name]=(fac*(1-b1)*p.grad/den).detach().cpu()
    return hist,cur


def mixed_curvature(e,rows,h,c):
    """Exact autograd mixed Hessian contraction on a fixed monitor subset.
    Derivatives at unmodified weights; does not perform a virtual optimizer step.
    """
    params=tuple(e.params.values());names=list(e.params);vals=[]
    for row in rows:
        loss=e.loss_rows([row]).mean()
        g=torch.autograd.grad(loss,params,create_graph=True)
        gh=sum((a*h[n].to(a.device)).sum() for n,a in zip(names,g))
        hv=torch.autograd.grad(gh,params,allow_unused=True)
        val=sum(dot(v,c[n].to(v.device)) for n,v in zip(names,hv) if v is not None)
        vals.append(val);del loss,g,gh,hv
    return dict(h_H_c=float(np.mean(vals)),entities=[r['entity'] for r in rows],per_entity=vals,
        convention='Current monitor-subset loss Hessian; history/current use actual shared updated Adam denominator.')


def evaluate(e,data,batch):
    out={}
    with torch.no_grad():
        for split in SPLITS:
            rows=[]
            for i in range(0,len(data[split]),batch):
                rr=data[split][i:i+batch];inp,q,lab=collate(rr,e.tok.pad_token_id,e.c.device)
                h=e.model.model(**inp,use_cache=False,return_dict=True).last_hidden_state[:,-1,:]
                lp=e.model.lm_head(h).double().log_softmax(-1)
                kl=(q*(q.log()-lp[:,lab])).sum(-1);mass=-lp[:,lab].logsumexp(-1);margin=lp[:,lab[0]]-lp[:,lab[1]]
                rows.extend(dict(entity=r['entity'],q0=r['q'][0],loss=float(l),support=float(m),margin=float(z)) for r,l,m,z in zip(rr,kl,mass,margin))
            out[split]=dict(mean=float(np.mean([r['loss'] for r in rows])),rows=rows)
    return out


