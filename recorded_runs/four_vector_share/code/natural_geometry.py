    gs=[]
    for seed in seeds:
        tr=[r for r in geometry_scores if r['seed']!=seed];te=[r for r in geometry_scores if r['seed']==seed]
        if len(tr)<16 or len(te)<4:continue
        for label,indices in [('norm_only',[0]),('norm_channels',[0,1,2,3]),('norm_channels_frames',list(range(7)))]:
            x=np.array([r['x'] for r in tr])[:,indices];xt=np.array([r['x'] for r in te])[:,indices];y=np.array([r['y'] for r in tr]);yt=np.array([r['y'] for r in te])
            mu=x.mean(0);sd=np.maximum(x.std(0),1e-12);x=np.c_[np.ones(len(x)),(x-mu)/sd];xt=np.c_[np.ones(len(xt)),(xt-mu)/sd];penalty=np.eye(x.shape[1]);penalty[0,0]=0
            coef=np.linalg.solve(x.T@x+penalty,x.T@y)
            gs.append(dict(heldout_seed=seed,model=label,n=len(te),MSE=float(np.mean((xt@coef-yt)**2)),constant_training_mean_MSE=float(np.mean((yt-y.mean())**2))))
    atomic_json(dict(scores=gs,features=['update_norm','history_current_cosine','g_h','g_c','monitor_mean_subspace_angle','monitor_mean_shift_norm','monitor_mean_local_projection'],note='All models compared on the same scheduled geometry points. Features use A-valid monitor identities; next-step target is all-entity A-test loss change. Fixed ridge=1, fit and normalization exclude evaluation seed. No tuning on A-test.'),out/'frame_prediction.json')
    atomic_json(dict(scores=scores,note='Exploratory next-update prediction, ridge penalty fixed at 1; normalization fitted only on other seeds. Few seeds and shared tasks limit inference. Scheduled frame comparisons are in frame_prediction.json.'),out/'lagged_prediction.json')


