def save_checkpoint(e,folder,step,s):
    # One rolling checkpoint per seed. Source checkpoints are never modified.
    path=folder/'resume.pt';tmp=folder/'resume.pt.tmp'
    needed=3*e.pb+256*1024**2
    if shutil.disk_usage(folder).free<needed+s['minimum_free_gb']*1024**3:raise Pause('Insufficient reserve for atomic rolling checkpoint; last committed checkpoint remains usable')
    torch.save(dict(engine=e.pack(),step=step,torch_rng=torch.get_rng_state(),cuda_rng=torch.cuda.get_rng_state_all() if torch.cuda.is_available() else []),tmp)
    os.replace(tmp,path)


def restore_seed(e,s,seed):
    folder=Path(s['output'])/f'seed{seed}';folder.mkdir(exist_ok=True)
    cp=folder/'resume.pt'
    if cp.exists():
        z=load(cp);e.restore(z['engine']);step=int(z['step']);torch.set_rng_state(z['torch_rng'])
        if z.get('cuda_rng') and torch.cuda.is_available():torch.cuda.set_rng_state_all(z['cuda_rng'])
    else:
        e.restore(load(Path(s['source'])/f'seed{seed}/anchor.pt'))
        if e.c.transition=='reset':e.reset_optimizer()
        step=0
    return step,folder


def natural_step(e,data,s,seed,step,monitor,ctl):
    start=time.time();ctl.check();ctl.pulse(seed=seed,step=step,phase='monitor task-A gradient')
    mon=[r for r in data['A_valid'] if r['entity'] in monitor]
    ga=mean_gradient(e,mon)
    ctl.pulse(phase='original B minibatch gradient')
    train=e.gradient(minibatches(data,'B',seed,step,e.c));h,c=channels(e)
    before={n:p.detach().cpu().clone() for n,p in e.params.items()}
    records={};sums=dict(h2=0.,c2=0.,hc=0.,g2=0.,g_h=0.,g_c=0.,g_delta=0.,delta2=0.,reconstruction_error2=0.)
    for n,p in e.params.items():
        if n not in h:continue
        a,b,g=h[n],c[n],ga[n]
        rr=dict(group=group(n),shape=list(p.shape),h2=dot(a,a),c2=dot(b,b),hc=dot(a,b),g2=dot(g,g),g_h=dot(g,a),g_c=dot(g,b))
        records[n]=rr
        for k in ['h2','c2','hc','g2','g_h','g_c']:sums[k]+=rr[k]
    curve=None
    if s['curvature_every'] and step%s['curvature_every']==0:
        ctl.check();ctl.pulse(phase='mixed history/current Hessian contraction')
        curve=mixed_curvature(e,mon[:s['curvature_entities']],h,c)
    # Measurement autograd calls above do not touch the clipped .grad used here.
    ctl.check();ctl.pulse(phase='natural Adam update')
    e.opt.step();e.opt.zero_grad(set_to_none=True)
    delta={}
    for n,p in e.params.items():
        d=p.detach().cpu()-before[n];delta[n]=d
        if n not in records:continue
        rr=records[n];rr.update(delta2=dot(d,d),g_delta=dot(ga[n],d),reconstruction_error2=dot(d-h[n]-c[n],d-h[n]-c[n]),
            weight_norm_before=math.sqrt(dot(before[n],before[n])),weight_norm_after=math.sqrt(dot(p.detach(),p.detach())),
            weight_cosine_before_after=cos(before[n],p.detach().cpu()))
        for k in ['delta2','g_delta','reconstruction_error2']:sums[k]+=rr[k]
    group_totals={}
    for rr in records.values():
        g=group_totals.setdefault(rr['group'],{k:0. for k in ['h2','c2','hc','g_h','g_c','delta2','g_delta']})
        for k in g:g[k]+=rr[k]
    sums['history_current_cosine']=sums['hc']/max(math.sqrt(sums['h2']*sums['c2']),1e-30)
    sums['channel_reconstruction_relative_error']=math.sqrt(sums['reconstruction_error2']/max(sums['delta2'],1e-30))
    del h,c,before,ga
    ctl.pulse(phase='all-entity A/B evaluation')
    evaluation=evaluate(e,data,s['eval_batch'])
    if step%s['derivative_every']==0:
        ctl.pulse(phase='post-update monitor gradient')
        post=mean_gradient(e,mon);sums['post_gradient_dot_delta']=sum(dot(post[n],delta[n]) for n in post)
        sums['directional_gradient_change']=sums['post_gradient_dot_delta']-sums['g_delta'];del post
    del delta
    return dict(seed=seed,step=step,evaluation=evaluation,channels=sums,parameter_groups=group_totals,matrices=records,mixed_curvature=curve,
        training=dict(raw_gradient_norm=train['raw_norm'],clip=train['clip'],weight_decay=0),seconds=time.time()-start)


def identity(s):
    x={k:v for k,v in s.items() if k not in ['hours','reserve_minutes','minimum_free_gb','max_measurement_gb','output']}
    return hashlib.sha256(json.dumps(x,sort_keys=True).encode()).hexdigest()


def run(s):
    import fcntl
    out=Path(s['output']);out.mkdir(parents=True,exist_ok=True)
    with (out/'worker.lock').open('a') as lock:
        try:fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
        except BlockingIOError:return
        ctl=Control(s);e=None;con=None;folder=None;completed_step=None
        try:
            c=validate(s);monitor,held=split_ids(s,c);con=db_open(out)
            atomic_json(dict(monitor_entities=monitor,heldout_geometry_entities=held,note='Disjoint diagnostic identities, not unseen model-training identities.'),out/'partition.json')
            atomic_json(dict(python=sys.version,torch=torch.__version__,platform=platform.platform(),cuda=torch.version.cuda,
                device=torch.cuda.get_device_name(0) if torch.cuda.is_available() else 'CPU'),out/'hardware.json')
            ctl.pulse(phase='loading original OLMo model')
            e=Engine(c)
            required=(len(s['seeds'])+1)*3*e.pb+s['minimum_free_gb']*1024**3
            if not list(out.glob('seed*/resume.pt')) and shutil.disk_usage(out).free<required:raise Pause(f'Need approximately {required/1024**3:.1f} GiB free for bounded rolling checkpoints plus reserve')
            # Resume positions are cheap JSON mirrors of committed checkpoint steps.
            cursors={seed:read(out/f'seed{seed}/committed.json',{}).get('step',0) for seed in s['seeds']}
            while any(v<s['end_step'] for v in cursors.values()):
                for seed in s['seeds']:
                    if cursors[seed]>=s['end_step']:continue
                    ctl.check();ctl.pulse(seed=seed,phase='loading seed continuation')
                    completed_step,folder=restore_seed(e,s,seed);cursors[seed]=completed_step
                    data=make_data(e.tok,c,seed)
                    if digest(data)!=read(Path(s['source'])/f'seed{seed}/data.json')['hash']:raise ValueError('Source task data hash differs; refusing an incomparable run.')
                    # Remove measurements newer than a durable checkpoint, then deterministically replay.
                    con.execute('DELETE FROM steps WHERE seed=? AND step>?',(seed,completed_step));con.commit()
                    for f in folder.glob('snapshot_*.npz'):
                        if int(f.stem.split('_')[-1])>completed_step:f.unlink()
                    while completed_step<s['start_step']:
                        ctl.check();e.gradient(minibatches(data,'B',seed,completed_step+1,c));e.opt.step();e.opt.zero_grad(set_to_none=True);completed_step+=1
                    anchor=folder/'baseline.npz'
                    if not anchor.exists():
                        ctl.pulse(phase='baseline diagnostics',step=completed_step)
                        arr,meta=capture(e,data,s,monitor,held,ctl);npz_save(anchor,arr);atomic_json(meta,folder/'geometry_entities.json')
                        atomic_json(evaluate(e,data,s['eval_batch']),folder/'baseline_losses.json')
                        save_checkpoint(e,folder,completed_step,s);atomic_json(dict(step=completed_step),folder/'committed.json')
                    base=npz_read(anchor);meta=read(folder/'geometry_entities.json')
                    snaps=sorted(folder.glob('snapshot_*.npz'));previous=npz_read(snaps[-1]) if snaps else base
                    end=min(completed_step+s['chunk_steps'],s['end_step'])
                    for step in range(completed_step+1,end+1):
                        measured_start=time.time()
                        rec=natural_step(e,data,s,seed,step,monitor,ctl)
                        # The natural update is now complete even if an optional diagnostic is interrupted.
                        completed_step=step
                        if step%s['geometry_every']==0:
                            try:
                                arr,meta=capture(e,data,s,monitor,held,ctl)
                                ctl.pulse(phase='topology, frames and sampled matrix spectra')
                                rec['geometry']=geometry_analysis(arr,base,previous,meta,s,seed)
                                rec['sampled_matrix_spectra']=sampled_matrices(e,s,seed)
                                monitor_frames=[]
                                for key in arr:
                                    if key.startswith('A_valid__') and key.endswith('__x'):
                                        prefix=key[:-1]
                                        fm=frame_metrics(arr[key],base[key],arr[prefix+'lossgrad'],base[prefix+'lossgrad'],s['frame_rank'])
                                        angles=fm['principal_angles_degrees']
                                        monitor_frames.append([float(np.mean(angles)) if angles else 0.,fm['mean_shift_norm'],float(np.mean(fm['old_sensitivity_dot_displacement']))])
                                rec['monitor_frame_features']=np.mean(monitor_frames,axis=0).tolist()
                                npz_save(folder/f'snapshot_{step:05d}.npz',arr);previous=arr
                            except Pause as exc:
                                rec['geometry_incomplete']=str(exc)
                                con.execute('INSERT OR REPLACE INTO steps VALUES (?,?,?)',(seed,step,json.dumps(rec,allow_nan=False)));con.commit();raise
                        before_eval=read(folder/'baseline_losses.json') if step==s['start_step']+1 else None
                        if before_eval is None:
                            row=con.execute('SELECT record FROM steps WHERE seed=? AND step=?',(seed,step-1)).fetchone()
                            before_eval=json.loads(row[0])['evaluation'] if row else None
                        if before_eval:
                            prior=[r['loss'] for r in before_eval['A_valid']['rows'] if r['entity'] in monitor]
                            after=[r['loss'] for r in rec['evaluation']['A_valid']['rows'] if r['entity'] in monitor]
                            change=float(np.mean(after)-np.mean(prior));rec['monitor_loss_change']=change;rec['monitor_finite_remainder']=change-rec['channels']['g_delta']
                        rec['total_measurement_seconds']=time.time()-measured_start
                        con.execute('INSERT OR REPLACE INTO steps VALUES (?,?,?)',(seed,step,json.dumps(rec,allow_nan=False)));con.commit()
                        ctl.pulse(phase='step measurements saved',seed=seed,step=step)
                        if step%s['checkpoint_every']==0:
                            save_checkpoint(e,folder,completed_step,s);atomic_json(dict(step=completed_step),folder/'committed.json');ctl.storage()
                        ctl.check()
                    save_checkpoint(e,folder,completed_step,s);atomic_json(dict(step=completed_step),folder/'committed.json');cursors[seed]=completed_step
                    report(out);del base,previous;gc.collect()
            final='complete';message='All configured natural trajectories finished.'
        except Pause as exc:
            final='paused';message=str(exc)
            if e is not None and folder is not None and completed_step is not None:
                try:save_checkpoint(e,folder,completed_step,s);atomic_json(dict(step=completed_step),folder/'committed.json')
                except Pause as save_error:message+='; '+str(save_error)
        except Exception:
            final='failed';message=traceback.format_exc();(out/'error.txt').write_text(message)
            # Do not commit potentially half-measured/half-updated state on unexpected failure.
        finally:
            if con is not None:con.close()
        try:report(out)
        except Exception:(out/'report_error.txt').write_text(traceback.format_exc())
        atomic_json(dict(status=final,message=message,last_progress=time.time()),out/'status.json')
        try:export(out)
        except Exception:(out/'export_error.txt').write_text(traceback.format_exc())


def records(output):
    p=Path(output)/'measurements.sqlite'
    if not p.exists():return []
    with sqlite3.connect(f'file:{p}?mode=ro',uri=True) as con:return [json.loads(r[0]) for r in con.execute('SELECT record FROM steps ORDER BY seed,step')]


def report(output):
    out=Path(output);rr=records(out)
    if not rr:return
    flat=[]
    for r in rr:
        row=dict(seed=r['seed'],step=r['step'],seconds=r['seconds'],**{sp:r['evaluation'][sp]['mean'] for sp in SPLITS},**r['channels'])
        row.update(monitor_loss_change=r.get('monitor_loss_change'),monitor_finite_remainder=r.get('monitor_finite_remainder'))
        flat.append(row)
    fields=sorted(set().union(*(r.keys() for r in flat)))
    with (out/'trajectory.csv').open('w',newline='') as f:
        w=csv.DictWriter(f,fieldnames=fields);w.writeheader();w.writerows(flat)
    lines=['NATURAL TRAJECTORY — unchanged original Adam training','Measurements are observational; diagnostics do not establish a universal cause.']
    for seed in sorted(set(r['seed'] for r in rr)):
        rows=[r for r in rr if r['seed']==seed];last=rows[-1]
        lines.append(f"Seed {seed}: {len(rows)} measured updates; last step {last['step']}; A_test {last['evaluation']['A_test']['mean']:.6f}; B_test {last['evaluation']['B_test']['mean']:.6f}")
        events=sorted([r for r in rows if 'monitor_loss_change' in r],key=lambda r:r['monitor_loss_change'],reverse=True)[:3]
        lines.append('Largest A-monitor increases: '+', '.join(f"step {r['step']}: {r['monitor_loss_change']:+.6f}" for r in events))
    lines += ['Event ranking uses A-valid monitor identities. A-test data are not used to select the events.',
        'All matrix step statistics cover unique named parameters; spectra are coordinate samples, not full matrix spectra.',
        'Hidden sensitivities describe final-token residual sites with other token positions held fixed.',
        'PH is invariant to global rotations/translations. Task semimetric is frozen at baseline; it is not Fisher.',
        'Native Adam history/current channels and QK/gate versus content parameter groups are distinct decompositions.',
        'Only baseline and scheduled last-token activations/sensitivities are retained. Full token arrays and historical checkpoints are not retained.']
    (out/'REPORT.txt').write_text('\n'.join(lines)+'\n')
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    seeds=sorted(set(r['seed'] for r in rr));fig,axes=plt.subplots(len(seeds),3,figsize=(14,3.3*len(seeds)),squeeze=False)
    for i,seed in enumerate(seeds):
        rows=[r for r in rr if r['seed']==seed];x=[r['step'] for r in rows]
        for sp in ['A_test','B_test']:axes[i,0].plot(x,[r['evaluation'][sp]['mean'] for r in rows],label=sp)
        for field in ['g_h','g_c','g_delta']:axes[i,1].plot(x,[r['channels'][field] for r in rows],label=field)
        axes[i,2].plot(x,[r['channels']['history_current_cosine'] for r in rows],label='history/current cosine')
        for ax in axes[i]:ax.set_xlabel('Natural B update');ax.grid(alpha=.2);ax.legend(fontsize=8)
        axes[i,0].set_ylabel(f'Seed {seed} KL');axes[i,1].set_title('A-monitor first-order projections');axes[i,2].set_ylim(-1.05,1.05)
    fig.tight_layout();fig.savefig(out/'trajectory.png',dpi=160);plt.close(fig)
    # Honest held-out-seed exploratory prediction, no test-set hyperparameter tuning.
    lagged=[]
    for seed in seeds:
        rows=[r for r in rr if r['seed']==seed]
        for prev,nxt in zip(rows,rows[1:]):
            if nxt['step']!=prev['step']+1:continue
            lagged.append(dict(seed=seed,step=prev['step'],x=[math.sqrt(prev['channels']['delta2']),prev['channels']['history_current_cosine'],prev['channels']['g_h'],prev['channels']['g_c']],
                y=nxt['evaluation']['A_test']['mean']-prev['evaluation']['A_test']['mean']))
    scores=[]
    for seed in seeds:
        tr=[r for r in lagged if r['seed']!=seed];te=[r for r in lagged if r['seed']==seed]
        if len(tr)<12 or len(te)<4:continue
        for label,indices in [('update_norm_only',[0]),('norm_and_channels',[0,1,2,3])]:
            x=np.array([r['x'] for r in tr])[:,indices];xt=np.array([r['x'] for r in te])[:,indices];y=np.array([r['y'] for r in tr]);yt=np.array([r['y'] for r in te])
            mu=x.mean(0);sd=np.maximum(x.std(0),1e-12);x=np.c_[np.ones(len(x)),(x-mu)/sd];xt=np.c_[np.ones(len(xt)),(xt-mu)/sd]
